import { Banner, DemoDataNote } from "@/components/ui";
import { resultsFor } from "@/lib/data/results";

/**
 * Says where the scores on a screen come from, so the reader knows what to trust.
 *
 *   - a sample learner: the built-in sample data (the old preview note);
 *   - stored results written by the sample-results seed: real records, but generated, not from a headset;
 *   - stored results from a headset: nothing to say;
 *   - nothing stored yet: says so, rather than calling an empty screen "sample data".
 */
export async function ResultsNote({
  userId,
  sample,
  live,
}: {
  userId: string;
  /** What the sample data covers on this screen, for a sample learner. */
  sample?: string;
  /** What on this screen is live regardless (scheduled sessions). */
  live?: string;
}) {
  const data = await resultsFor(userId);
  const liveLine = live ? <> Live: {live}.</> : null;

  if (data.source === "sample") return <DemoDataNote sample={sample} live={live} />;

  if (data.source === "database" && data.sessions.length > 0) {
    const versions = new Set(
      [...data.reportBySession.values()].map((r) => r.stored?.scoringVersion).filter(Boolean) as string[],
    );
    const generated = [...versions].some((v) => v.endsWith("-sample"));
    if (!generated) return null;
    return (
      <Banner tone="info" title="Sample results">
        These runs and reports were generated by the sample-results seed and scored with the sample rules (
        {[...versions].join(", ")}), not recorded by a headset. They are saved records.{liveLine}
      </Banner>
    );
  }

  return (
    <Banner tone="info" title="No results yet">
      Scores and reports appear here once a headset run has been scored.{liveLine}
    </Banner>
  );
}
